import { Memory, Alert, Conversation } from "../models.js";

/**
 * Caregiver & Doctor Reporting Agent:
 * Formats daily health summaries, lists active safety alerts, or looks up recent memories on demand.
 */
export async function handleCaregiverQuery(patientId, queryText) {
  const q = (queryText || "").toLowerCase().trim();

  // 1. Safety Alerts Request
  if (q.includes("alert") || q.includes("warning") || q.includes("emergency")) {
    const alerts = await Alert.find({ patientId }).sort({ timestamp: -1 }).limit(5).lean();
    if (alerts.length === 0) {
      return `🩺 *AnchorCare Doctor Report for ${patientId}*\n\n✅ *No safety alerts on file.* The patient has had no reported distress or dosage inquiries.`;
    }

    let report = `🩺 *Active Safety Alerts for ${patientId}* (Last ${alerts.length}):\n\n`;
    alerts.forEach((a, i) => {
      const time = new Date(a.timestamp).toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" });
      report += `${i + 1}. *[${a.type}]* at ${time}\n   ${a.message}\n\n`;
    });
    return report;
  }

  // 2. Daily Summary Request
  if (q.includes("summary") || q.includes("today") || q.includes("status") || q.includes("report")) {
    const memories = await Memory.find({ patientId }).sort({ createdAt: -1 }).limit(8).lean();
    const alertsCount = await Alert.countDocuments({ patientId });

    if (memories.length === 0) {
      return `📋 *Daily Summary for ${patientId}*\n\nNo memory events recorded yet today.`;
    }

    let summary = `📋 *Daily AnchorCare Summary for ${patientId}*\n`;
    summary += `Total Recorded Events: ${memories.length} | Safety Flags: ${alertsCount}\n\n`;

    memories.forEach((m, idx) => {
      const time = m.when ? (isNaN(Date.parse(m.when)) ? m.when : new Date(m.when).toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" })) : "Recorded";
      const whoStr = m.who && m.who.length > 0 ? ` (with ${m.who.join(", ")})` : "";
      const locStr = m.where ? ` @ ${m.where}` : "";
      summary += `• *${time}* — ${m.what}${whoStr}${locStr}\n`;
    });

    summary += `\n_Generated by AnchorCare Multi-Agent Sentinel_`;
    return summary;
  }

  // Default Help
  return `🩺 *AnchorCare Caregiver Agent*\n\nYou can send commands like:\n• *summary* — Get today's activity and memory timeline\n• *alerts* — View recent safety, injury, or dosage alerts\n• Or tell me any memory (e.g. "Arthur went to the park") to log it directly into his memory bank.`;
}
